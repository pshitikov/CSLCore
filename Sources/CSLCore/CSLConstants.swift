import SwiftUI

/// A namespace for constants used throughout the CSL module.
public enum CSLConstants {
    
    // MARK: - General Constants

    /// The delay before inserting a progress view, in seconds.
    public static let progressViewInsertionDelay: TimeInterval = 2

    /// The standard height of the search bar.
    public static let searchBarHeight: CGFloat = 36

    /// The bundle associated with the current module.
    public static let module: Bundle = .module
}

